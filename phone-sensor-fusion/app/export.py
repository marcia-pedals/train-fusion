"""Export what the phone app's online inference needs (ios/TrainRecorder/Inference/):

  ios/TrainRecorder/model.json                the fitted model (params/all.json) with
      everything that can be precomputed already precomputed (transition matrix, level
      means per state, table lookups per speed, filter coefficients, FFT windows, bin
      lists), plus the track model for the station layer. Checked in: the app bundles it.
  data/phone-sensor-fusion/app/<id>.ref.json  per-second features of each recording as
      this pipeline computes them, to check the app's port against (app/compare.py).

The app re-implements the feature extraction and the forward filter in Swift; nothing is
shared with this code except this file's output. The app is experimental: its format may
change freely, and nothing has to stay compatible.

    python -m app.export
"""

import json

import numpy as np
from scipy import signal

from common import paths
from features import comb, frames, phone_state
from labels.frames import CLOSE_CHIME, OPEN_CHIME
from maps import track as trackmod
from model import emissions, fit, states, stations

OUT = paths.REPO / "ios" / "TrainRecorder" / "model.json"
N_ST, N_V = states.N_STOPPED, states.N_V


def r(x, nd=5):
    return np.round(np.asarray(x, dtype=float), nd).tolist()


def level(q):
    if not q:
        return None
    knots, mean = np.asarray(q["knots"]), np.asarray(q["mean"])
    mu = np.r_[np.full(N_ST, mean[0]), np.interp(states.V_MOVING, knots[1:], mean[1:])]
    return {"mu": r(mu, 3), "sd": q["sd"], "weight": q["weight"]}


def comb_tables(p, f, pooled):
    """Per partial: for every speed state, the spectrum bin to read (-1 = off the end) and
    the table row; the table; and how much extra max-pooling the lookup needs."""
    if not p:
        return None
    df = f[1] - f[0]
    band = np.digitize(states.V_MOVING, comb.V_EDGES)
    out = []
    for ratio, table in zip(p["ratios"], p["llr"]):
        idx = np.round(ratio * states.V_MOVING / df).astype(int)
        idx[(idx < 1) | (idx >= len(f))] = -1
        extra = int(np.ceil(ratio * states.DV / (2 * df))) - pooled
        out.append({"ratio": ratio, "bin": idx.tolist(), "band": band.tolist(), "table": r(table, 3), "extra": max(extra, 0)})
    return {"partials": out, "z_edges": comb.Z_EDGES.tolist()}


def chime_bins(f, fc, half=25.0, bg=(100.0, 400.0)):
    return {"in": np.flatnonzero(np.abs(f - fc) <= half).tolist(),
            "side": np.flatnonzero((np.abs(f - fc) >= bg[0]) & (np.abs(f - fc) <= bg[1])).tolist()}


def main():
    p = json.loads((paths.PARAMS / "all.json").read_text())
    tr = trackmod.load()
    A = emissions.transition(p)
    nz = np.argwhere(A > 0)
    f_chime = np.fft.rfftfreq(frames.CHIME_NWIN, 1 / frames.FS)
    f_tone = np.fft.rfftfreq(frames.TONE_NFFT, 1 / frames.FS)
    n_tone = int(np.sum(f_tone <= frames.TONE_FMAX))
    f_acc = np.fft.rfftfreq(frames.ACC_NFFT, 1 / frames.IMU_FS)
    wheel = {name: comb_tables(emissions.wheel_tables(p, name)[0], f_acc, frames.ACC_POOL_BINS) for name in ("resting", "held")}
    heading = np.degrees(np.unwrap(np.radians(tr.heading)))
    model = {
        "note": "generated by phone-sensor-fusion/app/export.py from params/all.json; do not edit",
        "n_stopped": N_ST, "n_v": N_V, "dv": states.DV, "v": r(states.V, 2),
        "mode": states.MODE.tolist(), "prior": r(emissions.prior(), 7),
        "transitions": [[int(i), int(j), round(float(A[i, j]), 7)] for i, j in nz],
        "open_chime_state": states.idx(OPEN_CHIME), "close_chime_state": states.idx(CLOSE_CHIME),
        "chime": {name: {"log_in": r(np.log(p["chime"][name]["in"])), "log_out": r(np.log(p["chime"][name]["out"]))}
                  for name in ("open", "close")},
        "chime_edges": fit.CHIME_EDGES,
        "tone": comb_tables(p["tone"], f_tone[:n_tone], frames.TONE_POOL_BINS),
        "wheel": wheel,
        "level": {k.replace("/", "_"): level(v) for k, v in p["level"].items()},
        "level_outlier": emissions.LEVEL_OUTLIER, "level_floor": emissions.LEVEL_FLOOR,
        "accel": {"sd": p["accel"]["sd"], "outlier": emissions.ACCEL_OUTLIER[0], "sd_outlier": emissions.ACCEL_OUTLIER[1]},
        "phone": {"mean": [p["phone"][s]["mean"] for s in phone_state.STATES],
                  "sd": [p["phone"][s]["sd"] for s in phone_state.STATES], "switch": p["phone"]["switch_per_s"]},
        "dsp": {
            "fs": frames.FS,
            "decimate_taps": r(signal.firwin(95, 7400.0, fs=48000), 8),  # 48 kHz -> 16 kHz, by 3
            "chime": {"nwin": frames.CHIME_NWIN, "hop": frames.CHIME_HOP, "db": frames.CHIME_DB,
                      "min_partials": frames.CHIME_MIN_PARTIALS,
                      "window": r(signal.get_window(("tukey", 0.25), frames.CHIME_NWIN), 7),
                      "open": [chime_bins(f_chime, fc) for fc in frames.CHIME_PARTIALS["open"]],
                      "close": [chime_bins(f_chime, fc) for fc in frames.CHIME_PARTIALS["close"]]},
            "tone": {"nwin": frames.TONE_NWIN, "nfft": frames.TONE_NFFT, "hop": frames.TONE_HOP, "bins": n_tone,
                     "median": int(frames.TONE_BG_HZ / (f_tone[1] - f_tone[0])) | 1, "pool": 2 * frames.TONE_POOL_BINS + 1,
                     "window": r(signal.get_window(("tukey", 0.25), frames.TONE_NWIN), 7)},
            "accel": {"nwin": frames.ACC_NWIN, "nfft": frames.ACC_NFFT, "bins": len(f_acc),
                      "median": int(frames.ACC_BG_HZ / (f_acc[1] - f_acc[0])) | 1, "pool": 2 * frames.ACC_POOL_BINS + 1,
                      "window": r(signal.get_window(("tukey", 0.25), frames.ACC_NWIN), 7)},
            "rumble_sos": r(signal.butter(4, frames.RUMBLE_BAND, btype="band", fs=frames.FS, output="sos"), 12),
            "vib_sos": [r(signal.butter(4, b, btype="band", fs=frames.IMU_FS, output="sos"), 12) for b in frames.VIB_BANDS],
        },
        "track": {
            "stations": list(tr.stations), "station_s": r(tr.station_s, 0),
            "step": float(tr.s[1] - tr.s[0]), "curvature": r(tr.curvature, 7), "heading_south": r(heading, 2),
            "elev_step": float(tr.elev_s[1] - tr.elev_s[0]), "elevation": r(tr.elev, 2),
            "declination": trackmod.DECLINATION_DEG,
        },
        "stations": {k: getattr(stations, k) for k in (
            "P_SKIP", "DIST_REL", "DIST_ABS", "P_UNEXPLAINED", "YAW_SD", "YAW_OUTLIER", "YAW_WEIGHT", "MIN_YAW_SPEED",
            "HEADING_SD", "HEADING_OUTLIER", "HEADING_WEIGHT", "HEADING_P_OFF", "BARO_SD", "BARO_OUTLIER", "BARO_WEIGHT",
            "MIN_BARO_SPEED", "P_FALSE")},
    }
    OUT.write_text(json.dumps(model, separators=(",", ":")))
    print("wrote", OUT, f"{OUT.stat().st_size / 1e6:.2f} MB")

    for rid in paths.recording_ids():
        f = frames.load(rid)
        ref = {"open_chime": r(f["open_chime"], 3), "close_chime": r(f["close_chime"], 3), "rumble_db": r(f["rumble_db"], 2),
               "vib_low": r(f["vib_db"][:, 0], 2), "vib_high": r(f["vib_db"][:, 1], 2), "gyro_rms": r(f["gyro_rms"], 3),
               "acc_mean": r(f["acc_mean"], 4),
               "tone_spec": {str(b): r(f["tone_spec"][:, b], 2) for b in (150, 300, 475, 700)},
               "accel_spec": {str(b): r(f["accel_spec"][:, b], 2) for b in (100, 250, 500)}}
        if "baro_alt" in f:
            ref["baro_alt"] = r(f["baro_alt"], 2)
        out = paths.derived("app", f"{rid}.ref.json")
        out.write_text(json.dumps(ref, separators=(",", ":")))
    print("wrote reference features to", paths.derived("app", "x").parent)


if __name__ == "__main__":
    main()
